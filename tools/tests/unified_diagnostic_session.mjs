import assert from 'node:assert/strict';
import { G } from '../../src/state.js';
import { recordAudioDiagnosticMarker } from '../../src/core/audio.js';
import { profileBeginFrame, profileExternalTiming, profileFinishFrame, profileRecord } from '../../src/core/perfdiagnostics.js';
import { addUnifiedDiagnosticMarker, clearUnifiedDiagnosticRecording, compactUnifiedDiagnosticReport, createCompressedDiagnosticZip, recordDeveloperDiagnosticEvent, resolveDeployedGitCommitId, startUnifiedDiagnosticRecording, stopUnifiedDiagnosticRecording, unifiedDiagnosticReport, unifiedDiagnosticStatus } from '../../src/core/developer-diagnostics.js';
import { recordSimulationTiming } from '../../src/core/perfdiagnostics.js';
import { TileMap } from '../../src/world/map.js';
import { addEffect, clearVfx, spawn, vfxDiagnosticReport } from '../../src/gfx/vfx.js';

G.settings.developerMode = false;
assert.equal(startUnifiedDiagnosticRecording(), false, 'recording stays off until Developer Mode is enabled');
G.settings.developerMode = true;
G.char = { name: 'Diagnostics Test', classId: 'paladin', level: 12 };
G.world = { id: 'synthetic-dungeon', kind: 'dungeon', depth: 12, biome: { name: 'Diagnostics Cave' }, time: 1,
  creatures: [], npcs: [], hazards: [], corpses: [], loot: [], environmentTraps: [], lifecycle: {} };
G.world.player = { isPlayer: true, x: 2.25, y: 3.5, z: 0, r: 0.3, moveVec: [1, 0], moving: true, channel: null, castLock: 0, attackTarget: null, interact: null, lootTarget: null };
G.input = { keys: new Set(['ShiftLeft', 'KeyW']), mouse: { x: 310, y: 220, left: true, right: false, leftPressed: false, rightPressed: false } };

assert.equal(startUnifiedDiagnosticRecording(), true, 'one action starts the unified session');
const sessionId = unifiedDiagnosticStatus().sessionId;
assert.ok(sessionId);
let fetchCount = 0;
const fakeFetch = async (url) => {
  fetchCount++;
  if (String(url).includes('src/data/build-version.js')) return { ok: true, text: async () => "export const GAME_BUILD_ID = 'fork-main-healthbar-artwork-2026-11-26';" };
  if (String(url).includes('/deployments?')) return { ok: true, json: async () => [{ sha: 'test-deployed-sha', statuses_url: 'https://mock/statuses' }] };
  return { ok: true, json: async () => [{ state: 'success' }] };
};
assert.equal(await resolveDeployedGitCommitId({ fetchImpl: fakeFetch, pageUrl: 'https://example.test/Velscour-PC/' }), 'test-deployed-sha');
assert.equal(fetchCount, 3, 'commit metadata is checked only when preparing an exported report');
assert.equal(recordAudioDiagnosticMarker('area-enter', { environment: 'Diagnostics Cave' }), true);
recordDeveloperDiagnosticEvent('area-enter', { worldId: 'new-world-context', kind: 'town', environment: 'New Area', depth: 23, inCombat: false }, 'game-event');
assert.equal(addUnifiedDiagnosticMarker('synthetic test marker'), true);
assert.equal(profileBeginFrame(16.67), true);
profileRecord('playerSkillAttempt', 2.5);
profileRecord('playerWalkTo', 1.25);
profileRecord('depthQueueBuild', 3.5);
profileRecord('depthQueueSort', 0.75);
profileFinishFrame(G.world);
profileExternalTiming('synthetic.transition-stage', performance.now() - 2, { biome: 'Diagnostics Cave' });
class DiagnosticProbeEffect { constructor() { this.src = { name: 'Probe Owner' }; this.dur = 4; } update() { return true; } }
addEffect(new DiagnosticProbeEffect());
spawn({ type: 'diagnostic_probe', owner: { name: 'Probe Owner' }, x: 1, y: 1, life: 1, size: 2 });
let vfxReport = vfxDiagnosticReport();
assert.equal(vfxReport.effects.DiagnosticProbeEffect.created, 1, 'effect lifecycle is attributed by type at the centralized registration point');
assert.equal(vfxReport.effects.DiagnosticProbeEffect.baselineActive, 0, 'session-created effects are separated from preexisting effects');
assert.equal(vfxReport.particles.diagnostic_probe.created, 1, 'particle lifecycle is attributed by type at the centralized spawn point');
assert.equal(profileBeginFrame(100), true);
profileFinishFrame(G.world);
recordSimulationTiming({ source: 'raf', realElapsedMs: 120, simulatedMs: 50, discardedMs: 70 });
recordSimulationTiming({ source: 'catchup', realElapsedMs: 550, simulatedMs: 500, discardedMs: 50, updates: 15, workMs: 22 });
const collisionMap = new TileMap(8, 7); collisionMap.t.fill(1);
for (let y = 0; y < collisionMap.h; y++) collisionMap.block[y * collisionMap.w + 4] = 1;
G.world.map = collisionMap; G.world.player.x = 3.5; G.world.player.y = 3.5;
collisionMap.rememberPosition(G.world.player);
assert.ok(collisionMap.moveDash(G.world.player, 2, 0) < 2, 'diagnostic scenario blocks a dash at a wall');
G.world.player.x = 4.1;
assert.equal(collisionMap.recoverEmbedded(G.world.player), true, 'diagnostic scenario recovers an embedded player');
for (let i = 0; i < 4; i++) {
  await new Promise((resolve) => setTimeout(resolve, 105));
  assert.equal(profileBeginFrame(120 + i * 16.67, { rawDeltaMs: 16.67, simulationDeltaMs: 16.67 }), true);
  profileFinishFrame(G.world);
}
assert.equal(profileBeginFrame(performance.now(), { rawDeltaMs: 16.67, simulationDeltaMs: 16.67 }), true);
await new Promise((resolve) => setTimeout(resolve, 55));
profileFinishFrame(G.world);

let report = unifiedDiagnosticReport();
assert.equal(report.sessionId, sessionId);
assert.equal(report.recording.metadata.game.version, report.game.version);
assert.equal(report.sections.performance.sessionId, sessionId);
assert.equal(report.sections.audio.sessionId, sessionId);
assert.equal(report.sections.performance.completeSessionStatistics.framesObserved, 7);
assert.ok(report.sections.performance.completeSessionStatistics.completeFrameTimeDistributions.percentiles.frameMs.p50 !== null, 'whole-session frame percentiles are retained independently of the detailed-frame ring');
assert.equal(report.sections.performance.frames[0].playerSkillAttemptMs, 2.5, 'player skill attempts have explicit per-frame timing');
assert.equal(report.sections.performance.frames[0].playerWalkToMs, 1.25, 'player walkTo has explicit per-frame timing');
assert.equal(report.sections.performance.frames[0].depthQueueBuildMs, 3.5, 'depth queue construction is split from its sort');
assert.equal(report.sections.performance.frames[0].depthQueueSortMs, 0.75);
assert.equal(report.sections.performance.externalTimingSummary['synthetic.transition-stage'].count, 1, 'out-of-frame timings retain complete-session aggregate stats');
assert.equal(report.sections.performance.lifecycle.visualEffectSources.effects.DiagnosticProbeEffect.activeNow, 1, 'effect report distinguishes active objects from cumulative creates');
assert.ok(report.sections.performance.completeSessionStatistics.significantSpikes.length > 0, 'noteworthy pacing spikes survive in the complete-session aggregate');
assert.ok(report.timeline.markers.some((event) => event.details.marker === 'synthetic test marker'));
assert.ok(report.timeline.areaTransitions.some((event) => event.type === 'area-enter'));
assert.ok(report.timeline.areaTransitions.some((event) => event.worldId === 'new-world-context' && event.worldKind === 'town' && event.environment === 'New Area' && event.depth === 23), 'transition event top-level context follows the event destination, not the prior global world');
assert.equal(report.sections.performance.statisticsScope.elapsedSecondsReference, 'unified recording start; does not restart when the ring buffer wraps');
assert.ok(report.sections.performance.frames.at(-1).elapsedSeconds > 0.3, 'frame elapsed time remains relative to the unified session start');
assert.ok(report.sections.performance.incidents.some((incident) => incident.trigger === 'player-position-recovered' && incident.preEventSamples.length > 0 && incident.postEventSamples.length > 0), 'movement incidents retain bounded context before and after the event');
assert.ok(report.sections.performance.incidents.some((incident) => incident.trigger === 'automatic-frame-spike'), 'severe frame times automatically capture context');
assert.equal(report.sections.performance.incidentCaptureScope.captureLimit, 24);
assert.equal(report.sections.performance.incidents.find((incident) => incident.trigger === 'player-position-recovered').preEventSamples.at(-1).input.heldKeys.includes('ShiftLeft'), true, 'incident context stores held input');
assert.ok(report.sections.movementAndCollision.methodMetrics['movement.dash.calls'].accumulatedDetails.blockedAttempts >= 1, 'movement method metrics aggregate blocked movement');
assert.ok(report.sections.simulationTiming.summary.rafDiscardedMs >= 70, 'real versus simulated RAF delta is measured');
assert.equal(report.sections.simulationTiming.summary.catchupUpdates, 15);
for (let i = 0; i < 5050; i++) recordDeveloperDiagnosticEvent('synthetic-detail', { index: i }, 'simulation');
recordDeveloperDiagnosticEvent('synthetic-error', { message: 'preserved after detail limit' }, 'error');
report = unifiedDiagnosticReport();
assert.equal(report.recording.eventCounts.byType['synthetic-detail'], 5050, 'session event counters continue after detailed data is full');
assert.equal(report.recording.statisticsScope.detailedEventsStored, 5000);
assert.ok(report.recording.statisticsScope.detailedEventsDropped > 0);
assert.ok(report.timeline.errors.some((event) => event.type === 'synthetic-error'), 'important events remain available after detail truncation');
clearVfx();
vfxReport = vfxDiagnosticReport();
assert.equal(vfxReport.effects.DiagnosticProbeEffect.cleared, 1, 'area-style cleanup is recorded with its distinct removal reason');
const compact = compactUnifiedDiagnosticReport();
const compactBytes = new TextEncoder().encode(JSON.stringify(compact)).length;
assert.ok(compactBytes < 1_000_000, `compact report remains under 1 MB (actual ${compactBytes})`);
assert.equal(compact.compacting.withinTarget, true);
assert.ok(compact.performance.completeSessionStatistics.framesObserved >= 7, 'compact report retains complete performance aggregates');
assert.ok(compact.timeline.markers.some((event) => event.details.marker === 'synthetic test marker'), 'compact report retains user markers');
assert.ok(!Object.hasOwn(compact.movementAndCollision, 'incidentWindows') && !Object.hasOwn(compact.inputAndAction, 'incidentWindows'), 'compact report stores incident context once rather than duplicating it in both movement and input sections');
assert.equal(compact.performance.incidents[0].id, report.sections.performance.incidents[0].id, 'the shared incident context retains its stable ID');
assert.equal(compact.performance.frames, undefined, 'compact report omits ordinary frame dumps');
const zipBlob = await createCompressedDiagnosticZip(JSON.stringify({ sessionId, check: 'zip' }), 'test.json');
const zip = new Uint8Array(await zipBlob.arrayBuffer()), zipView = new DataView(zip.buffer);
assert.equal(zipView.getUint32(0, true), 0x04034b50, 'compressed export is a ZIP local-file archive');
assert.equal(zipView.getUint32(zip.length - 22, true), 0x06054b50, 'compressed export has a ZIP directory terminator');
const zipNameLength = zipView.getUint16(26, true), zipExtraLength = zipView.getUint16(28, true), zipCompressedLength = zipView.getUint32(18, true);
const zipBody = zip.subarray(30 + zipNameLength + zipExtraLength, 30 + zipNameLength + zipExtraLength + zipCompressedLength);
const { inflateRawSync } = await import('node:zlib');
assert.equal(JSON.parse(inflateRawSync(zipBody).toString('utf8')).sessionId, sessionId, 'ZIP body is valid raw-deflate JSON');

assert.equal(stopUnifiedDiagnosticRecording(), true);
G.settings.developerMode = false;
assert.equal(unifiedDiagnosticStatus().active, false);
report = unifiedDiagnosticReport();
assert.equal(report.sessionId, sessionId, 'stopping or disabling preserves the report');
assert.ok(report.recording.stoppedUtc);
clearUnifiedDiagnosticRecording();
assert.equal(unifiedDiagnosticStatus().hasRecording, false, 'Clear removes the combined session');
console.log('Unified diagnostic session start, event correlation, performance sample, stop, preserve, and clear passed.');
